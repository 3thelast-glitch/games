/**
 * NAQLA Apple Worm: original offline puzzle physics and permanent-head worm.
 * Curated independently authored maps; no proprietary game code or level assets.
 */
import { appleWormBlueprint, APPLE_WORM_STAGE_COUNT } from './levels.ts';

export interface Point { x:number; y:number }
export type Direction='up'|'down'|'left'|'right';
export type Phase='playing'|'won'|'lost';
export interface WormLevel {
 number:number; width:number;height:number;blocks:Point[];spikes:Point[];
 /** First fruit for legacy callers. Prefer apples for multi-fruit levels. */
 apple:Point; apples:Point[]; portal:Point;start:Point[];
}
export interface WormState {
 level:number;body:Point[];
 /** True ONLY once every fruit has been collected. */
 eaten:boolean;
 /** Indices of fruits eaten. Missing in earlier single-fruit saved games. */
 collectedApples?:number[];
 /** Old saves may contain this; no longer generated by the current physics. */
 pendingGrowth?:boolean;
 phase:Phase;moves:number;
}
export const WORM_LEVEL_COUNT=APPLE_WORM_STAGE_COUNT;
export const DIRECTIONS:Direction[]=['up','right','down','left'];
const STEPS:Record<Direction,Point>={
 up:{x:0,y:-1},down:{x:0,y:1},left:{x:-1,y:0},right:{x:1,y:0},
};
const same=(a:Point,b:Point)=>a.x===b.x&&a.y===b.y;
const key=(p:Point)=>p.x+':'+p.y;
const within=(p:Point,level:WormLevel)=>p.x>=0&&p.x<level.width&&p.y>=0&&p.y<level.height;
const toPoint=([x,y]:readonly[number,number]):Point=>({x,y});
const collectedFrom=(state:WormState, board:WormLevel):number[] =>
 state.collectedApples ? [...state.collectedApples]
 : state.eaten ? board.apples.map((_,i)=>i) : [];

export function wormLevel(number:number):WormLevel {
 const layout=appleWormBlueprint(number);
 const blocks=layout.blocks.map(toPoint);
 const apples=layout.fruits.map(toPoint);
 return {
  number,width:layout.width,height:layout.height,
  blocks,spikes:[],apple:apples[0]!,apples,
  portal:toPoint(layout.exit),start:layout.start.map(toPoint),
 };
}
export function startWorm(level=1):WormState {
 return {level,body:wormLevel(level).start.map(p=>({...p})),
  eaten:false,collectedApples:[],pendingGrowth:false,phase:'playing',moves:0};
}

export function moveWorm(state:WormState,direction:Direction):WormState {
 if(state.phase!=='playing'||!Object.prototype.hasOwnProperty.call(STEPS,direction))return state;
 const board=wormLevel(state.level);
 const blocked=new Set(board.blocks.map(key));
 const lethal=new Set(board.spikes.map(key));
 const delta=STEPS[direction];
 const head=state.body[0]!;
 const nextHead={x:head.x+delta.x,y:head.y+delta.y};
 if(!within(nextHead,board)||blocked.has(key(nextHead)))return state;
 if(state.body[1]&&same(state.body[1],nextHead))return state; // no instant reversal

 const previous=collectedFrom(state,board);
 const gathered=new Set(previous);
 const fruitIndex=board.apples.findIndex((apple,i)=>!gathered.has(i)&&same(nextHead,apple));
 // An apple is solid if approached vertically, and can support a falling worm.
 // It is consumed ONLY on a side-on mouth-first entry.
 if(fruitIndex>=0&&direction!=='left'&&direction!=='right')return state;
 if(fruitIndex>=0)gathered.add(fruitIndex);
 const grows=fruitIndex>=0||Boolean(state.pendingGrowth);
 const occupied=grows?state.body:state.body.slice(0,-1);
 if(occupied.some(p=>same(p,nextHead)))return state;
 let body=[nextHead,...state.body.map(p=>({...p}))];
 if(!grows)body=body.slice(0,-1);
 const collectedApples=[...gathered].sort((a,b)=>a-b);
 const eaten=collectedApples.length===board.apples.length;
 const pendingGrowth=false;
 let phase:Phase='playing';
 const winning=()=>eaten&&same(body[0]!,board.portal);
 const dead=()=>body.some(p=>!within(p,board)||lethal.has(key(p)));
 const remaining=board.apples.filter((_,i)=>!gathered.has(i));
 const supported=(parts:Point[])=>parts.some(p=>{
  const below={x:p.x,y:p.y+1};
  return blocked.has(key(below))||remaining.some(apple=>same(below,apple));
 });

 if(dead())phase='lost';
 else if(winning())phase='won';
 else{
  while(!supported(body)){
   const falling=body.map(p=>({x:p.x,y:p.y+1}));
   if(remaining.some(apple=>falling.some(p=>same(p,apple))))break;
   body=falling;
   if(dead()){phase='lost';break;}
   if(winning()){phase='won';break;}
  }
 }
 return {level:state.level,body,eaten,collectedApples,pendingGrowth,
  phase,moves:state.moves+1};
}

export function restoreWorm(value:unknown):WormState|null {
 if(!value||typeof value!=='object')return null;
 const state=value as Partial<WormState>;
 if(typeof state.level!=='number'||!Number.isInteger(state.level)||state.level<1||
  state.level>WORM_LEVEL_COUNT||!Array.isArray(state.body)||state.body.length<2||
  state.body.length>16||typeof state.eaten!=='boolean'||
  (state.pendingGrowth!==undefined&&typeof state.pendingGrowth!=='boolean')||
  (state.pendingGrowth===true&&(!state.eaten||state.phase==='won'))||
  !['playing','lost','won'].includes(state.phase??'')||
  typeof state.moves!=='number'||!Number.isSafeInteger(state.moves)||state.moves<0)return null;
 const board=wormLevel(state.level);
 if(!state.body.every(p=>p&&Number.isInteger(p.x)&&Number.isInteger(p.y)&&within(p,board)))return null;
 if(new Set(state.body.map(key)).size!==state.body.length)return null;
 if(state.body.some(p=>board.blocks.some(b=>same(p,b))))return null;
 let collected:number[];
 if(state.collectedApples!==undefined){
  if(!Array.isArray(state.collectedApples)||!state.collectedApples.every(i=>Number.isInteger(i)&&i>=0&&i<board.apples.length))return null;
  collected=[...new Set(state.collectedApples)].sort((a,b)=>a-b);
  if(collected.length!==state.collectedApples.length)return null;
 }else collected=state.eaten?board.apples.map((_,i)=>i):[];
 if(state.eaten!==(collected.length===board.apples.length))return null;
 if(state.phase==='won'&&!state.eaten)return null;
 return {level:state.level,body:state.body.map(p=>({...p})),eaten:state.eaten,
  collectedApples:collected,pendingGrowth:state.pendingGrowth===true,
  phase:state.phase!,moves:state.moves};
}

/** BFS hint solver and level-authoring validator; not needed for normal play. */
export function findWormSolution(initial:WormState,cap=30000):Direction[]|null {
 if(initial.phase==='won')return [];
 if(initial.phase==='lost')return null;
 const board=wormLevel(initial.level);
 const serialize=(s:WormState)=>collectedFrom(s,board).join(',')+
  (s.pendingGrowth?'g':'-')+':'+s.body.map(key).join('|');
 const seen=new Set([serialize(initial)]);
 const queue:{state:WormState;path:Direction[]}[]=[{state:initial,path:[]}];
 for(let index=0;index<queue.length&&index<cap;index++){
  const node=queue[index]!;
  for(const direction of DIRECTIONS){
   const next=moveWorm(node.state,direction);
   if(next===node.state||next.phase==='lost')continue;
   const path=[...node.path,direction];
   if(next.phase==='won')return path;
   const signature=serialize(next);
   if(seen.has(signature))continue;
   seen.add(signature);queue.push({state:next,path});
  }
 }
 return null;
}
