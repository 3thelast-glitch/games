export interface SourceTerrainCandidate {
  level:number;
  width:21;
  height:9;
  cells:readonly string[];
  provenance:'entry-frame-traced'|'heuristic-video-frame';
  mapFullyVerified:false;
  sourceWinningRouteVerified:false;
  readyForLiveGame:false;
}

export function appleWormSourceTerrainCandidate(level:number):SourceTerrainCandidate {
  if(!Number.isInteger(level)||level<1||level>TERRAIN_SAMPLES.length)
    throw new RangeError('Invalid source video level');
  const b64=TERRAIN_SAMPLES[level-1]!;
  const bytes=Uint8Array.from(atob(b64),ch=>ch.charCodeAt(0));
  if(bytes.length!==24)throw new Error('Malformed source video map sample');
  const bits=Array.from(bytes,b=>b.toString(2).padStart(8,'0')).join('').slice(3);
  const cells=Array.from({length:9},(_,y)=>bits.slice(y*21,(y+1)*21).replace(/0/g,'.').replace(/1/g,'#'));
  return {
    level,width:21,height:9,cells,
    provenance:level<=10?'entry-frame-traced':'heuristic-video-frame',
    mapFullyVerified:false,sourceWinningRouteVerified:false,
    readyForLiveGame:false,
  };
}
