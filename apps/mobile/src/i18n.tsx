export type Translate = (key: string) => string;
const Context = createContext<{ lang: Language; t: Translate }>({
  lang: 'en',
  t: (key) => en[key] ?? key,
});
export function I18n({ lang, children }: { lang: Language; children: ReactNode }) {
  return (
    <Context.Provider
      value={{
        lang,
        t: (key) => (lang === 'ar' ? ar[key] : en[key]) ?? en[key] ?? key,
      }}
    >
      {children}
    </Context.Provider>
  );
}
export const useI18n = () => useContext(Context);
